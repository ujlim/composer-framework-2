#!/usr/bin/env python3
"""Build an immutable, complete DAG candidate from pinned local Git checkouts."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from validate_pipeline_names import inspect_catalog


def digest(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def safe_path(name):
    path = PurePosixPath(name)
    if not name or path.is_absolute() or any(p in ("", ".", "..") for p in name.split("/")) or "\\" in name:
        raise ValueError(f"Unsafe relative path: {name!r}")
    if any(ord(c) < 32 for c in name):
        raise ValueError("Control character in file name")
    return path


def inventory(root):
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Symlink not allowed: {path}")
        if path.is_file():
            name = path.relative_to(root).as_posix()
            safe_path(name)
            if "__pycache__" in path.parts or path.suffix == ".pyc":
                raise ValueError(f"Generated bytecode in candidate: {path}")
            result[name] = digest(path.read_bytes())
    return result


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args], stderr=subprocess.PIPE)


def assemble(lock_path, output, source_commit=None):
    lock = json.loads(lock_path.read_text())
    if output.exists():
        raise ValueError("Output already exists; use a fresh candidate directory")
    entries = lock.get("sources")
    if not isinstance(entries, list) or not entries:
        raise ValueError("sources must be a nonempty list containing EVERY environment source")
    files, provenance, labels = {}, [], set()
    for source in entries:
        label = source["name"]
        if not isinstance(label, str) or not label or label in labels:
            raise ValueError("Source names must be nonempty and unique")
        labels.add(label)
        revision = source["commit"]
        if revision == "$COMMIT_SHA":
            revision = source_commit
        if not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ValueError(f"Source {label}: provide an exact 40-character commit SHA")
        repo = (lock_path.parent / source["repository"]).resolve()
        subdir = str(safe_path(source.get("dags", "dags")))
        resolved = git(repo, "rev-parse", revision + "^{commit}").decode().strip()
        if resolved != revision:
            raise ValueError(f"Commit mismatch: {label}")
        records = git(repo, "ls-tree", "-rz", revision, "--", subdir).split(b"\0")
        count = 0
        for record in records:
            if not record:
                continue
            header, raw_path = record.split(b"\t", 1)
            mode, kind, blob = header.decode().split()
            if kind != "blob" or mode not in {"100644", "100755"}:
                raise ValueError(f"Symlink/submodule not supported in {label}")
            path = raw_path.decode("utf-8")
            if not path.startswith(subdir + "/"):
                raise ValueError(f"Expected a DAG directory: {subdir}")
            relative = str(safe_path(path[len(subdir) + 1:]))
            if "__pycache__" in relative.split("/") or relative.endswith(".pyc"):
                raise ValueError("Tracked bytecode is not deployable")
            if ".airflowignore" in relative.split("/"):
                raise ValueError("Candidate .airflowignore is unsupported: it may hide validation failures")
            if relative.endswith(".py") and relative != "main.py" and not relative.startswith("framework/"):
                raise ValueError("Only the framework main.py entry point is supported")
            if relative in files:
                raise ValueError(f"Source ownership overlap: {relative}")
            files[relative] = git(repo, "cat-file", "blob", blob)
            count += 1
        if not count:
            raise ValueError(f"No DAG files at {label}:{subdir}")
        provenance.append({"name": label, "commit": revision, "dags": subdir})
    if "main.py" not in files or not any(name.startswith("framework/") for name in files):
        raise ValueError("Candidate must include exactly one framework and main.py")
    output.mkdir(parents=True)
    for name, data in files.items():
        target = output / "dags" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    manifest = {"schema": 1, "sources": provenance, "files": inventory(output / "dags")}
    manifest["release"] = digest(canonical(manifest))
    (output / "manifest.json").write_bytes(canonical(manifest))
    return manifest


def verify(output):
    manifest = json.loads((output / "manifest.json").read_text())
    unsigned = {key: value for key, value in manifest.items() if key != "release"}
    if manifest.get("schema") != 1 or digest(canonical(unsigned)) != manifest.get("release"):
        raise ValueError("Manifest digest mismatch")
    if inventory(output / "dags") != manifest["files"]:
        raise ValueError("Candidate bytes changed after assembly")
    return manifest


def validate(output):
    manifest = verify(output)
    report = inspect_catalog(output / "dags" / "pipelines")
    # Misspelled/nested config files must not disappear from a glob scan.
    for path in (output / "dags" / "pipelines").rglob("*"):
        if path.is_file() and path.stem.lower() == "config" and path.name != "config.yaml":
            report["errors"].append(f"Unsupported config filename: {path}")
    configs = {p.relative_to(output / "dags" / "pipelines").as_posix()
               for p in (output / "dags" / "pipelines").rglob("config.yaml")}
    recognized = {str(Path(e["config_path"]).relative_to((output / "dags" / "pipelines").resolve()))
                  for e in report["entries"]}
    if configs != recognized:
        report["errors"].append("Unrecognized or invalid config.yaml paths in candidate")
    if report["errors"]:
        raise ValueError("Full candidate validation failed:\n" + "\n".join(report["errors"]))
    for name in manifest["files"]:
        if name.endswith(".py"):
            compile((output / "dags" / name).read_bytes(), name, "exec")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    build = sub.add_parser("assemble")
    build.add_argument("--sources", type=Path, required=True)
    build.add_argument("--output", type=Path, required=True)
    build.add_argument("--source-commit")
    for name in ("verify", "validate"):
        cmd = sub.add_parser(name)
        cmd.add_argument("--candidate", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == "assemble":
            result = assemble(args.sources.resolve(), args.output, args.source_commit)
        else:
            result = globals()[args.command](args.candidate.resolve())
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
